// ── RefinedItemCard ───────────────────────────────────────────────────────────
// approved: null = default (treated as approved), true = explicitly approved, false = rejected

function RefinedItemCard({
  label,
  content,
  approved,
  onApprove,
  onReject,
}: {
  label: string;
  content: string;
  approved: boolean | null;
  onApprove: () => void;
  onReject: () => void;
}) {
  const isRejected = approved === false;
  const isApproved = approved === true || approved === null;

  return (
    <div
      className={`bg-slate-800/50 border rounded-xl p-5 transition-all ${
        isRejected
          ? "border-red-500/30 opacity-50"
          : "border-slate-700"
      }`}
    >
      <div className="flex items-start justify-between gap-3 mb-3">
        <p className="text-zinc-400 text-xs font-medium uppercase tracking-wide">{label}</p>
        {isRejected ? (
          <span className="text-xs font-semibold text-red-400 bg-red-500/10 border border-red-500/20 rounded-full px-2 py-0.5 shrink-0">
            Rejected
          </span>
        ) : (
          <span className="text-xs font-semibold text-emerald-400 bg-emerald-500/10 border border-emerald-500/20 rounded-full px-2 py-0.5 shrink-0">
            Approved
          </span>
        )}
      </div>
      <div className="text-zinc-200 text-sm leading-relaxed mb-4 space-y-1">
        {(() => {
          if (content.startsWith("experience_bullet:")) {
            const parts = content.replace("experience_bullet:", "").split("|").map(s => s.trim());
            if (parts.length >= 4) {
              return (
                <>
                  <p className="font-semibold text-indigo-300">{parts[1]} - {parts[0]}</p>
                  <p className="text-xs text-zinc-400 mb-2">{parts[2]}</p>
                  <ul className="list-disc pl-5 space-y-1">
                    {parts.slice(3).join(" | ").split("---").map((b, i) => (
                      <li key={i}>{b.trim()}</li>
                    ))}
                  </ul>
                </>
              );
            }
          } else if (content.startsWith("project:")) {
            const parts = content.replace("project:", "").split("—").map(s => s.trim());
            
            // If there's no "—", the AI might have just used "---" for everything
            const titlePart = parts[0];
            const bulletParts = parts.length > 1 ? parts.slice(1).join(" — ").split("---") : titlePart.split("---").slice(1);
            const actualTitle = parts.length > 1 ? titlePart : titlePart.split("---")[0];

            return (
              <>
                <p className="font-semibold text-indigo-300">{actualTitle}</p>
                <ul className="list-disc pl-5 space-y-1 mt-2">
                  {bulletParts.map((b, i) => (
                    <li key={i}>{b.trim()}</li>
                  ))}
                </ul>
              </>
            );
          } else if (content.startsWith("add_to_project:")) {
            const parts = content.replace("add_to_project:", "").split("|").map(s => s.trim());
            if (parts.length >= 2) {
              return (
                <>
                  <p className="font-semibold text-indigo-300">Added to Project: {parts[0]}</p>
                  <ul className="list-disc pl-5 space-y-1 mt-2">
                    {parts.slice(1).join(" | ").split("---").map((b, i) => (
                      <li key={i}>{b.trim()}</li>
                    ))}
                  </ul>
                </>
              );
            }
          }
          return <p>{content}</p>;
        })()}
      </div>
      <div className="flex gap-2">
        <button
          onClick={onApprove}
          className={`px-3 py-1.5 rounded-lg text-xs font-medium border transition-colors ${
            isApproved
              ? "bg-emerald-600 border-emerald-500 text-white"
              : "bg-slate-700 border-slate-600 text-zinc-400 hover:border-emerald-500/50 hover:text-emerald-400"
          }`}
        >
          Approve
        </button>
        <button
          onClick={onReject}
          className={`px-3 py-1.5 rounded-lg text-xs font-medium border transition-colors ${
            isRejected
              ? "bg-red-600 border-red-500 text-white"
              : "bg-slate-700 border-slate-600 text-zinc-400 hover:border-red-500/50 hover:text-red-400"
          }`}
        >
          Reject
        </button>
      </div>
    </div>
  );
}

