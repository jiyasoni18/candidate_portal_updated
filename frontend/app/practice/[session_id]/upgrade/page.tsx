// ── Gap Types & Helpers ───────────────────────────────────────────────────────

export type GapMode = "skill" | "experience" | "project";

export interface ExperienceEntry {
  company: string;
  jobTitle: string;
  startDate: string;
  endDate: string;
  description: string;
}

export interface GapAnswer {
  mode: GapMode;
  // skill gap
  hasExperience?: boolean | 'ai_generate';
  skillNote?: string;
  placementMode?: 'skill' | 'project_or_exp' | 'summary';
  projectType?: 'existing' | 'new' | 'skill';
  attachToExisting?: string; // name of existing project or company to attach skill note to
  projectName?: string;
  projectTech?: string;
  projectDescription?: string;
  projectUrl?: string;
  generateProject?: boolean;
  // follow-up clarification (set by AI)
  pendingQuestion?: string;
  pendingOptions?: string[];
  clarificationAnswer?: string;
}

function detectGapMode(_gap: string): GapMode {
  // All gaps in the card are skill-only now; experience/project are standalone sections
  return "skill";
}

function serializeGapAnswer(gap: string, answer: GapAnswer): string {
  if (answer.hasExperience === 'ai_generate') {
    const skill = gap.split(":")[0] || gap.split("—")[0] || "this skill";
    return `GENERATE_PROJECT: ${skill} | Description: Built a project demonstrating knowledge of ${skill} (Generated by AI).`;
  }

  if (answer.placementMode === 'summary') {
    let note = answer.skillNote || "";
    if (answer.clarificationAnswer) note += ` | Clarification: ${answer.clarificationAnswer}`;
    return `ADD_TO_SUMMARY: ${note}`;
  }
  
  // Project / Experience mode (or default)
  if (!answer.placementMode || answer.placementMode === 'project_or_exp' || answer.placementMode === 'skill') {
    // New project
    if (answer.projectType === 'new') {
      const skill = gap.split(":")[0] || gap.split("—")[0] || "this skill";
      let text = `GENERATE_PROJECT: ${skill} `;
      if (answer.projectName) text += `| Name: ${answer.projectName} `;
      if (answer.projectDescription) text += `| Description: ${answer.projectDescription} `;
      if (answer.projectUrl) text += `| URL: ${answer.projectUrl} `;
      if (answer.skillNote) text += `| User Knowledge: ${answer.skillNote}`;
      return text.trim();
    }
    
    // Existing project
    if (answer.projectType === 'existing' || !answer.projectType || answer.projectType === 'skill') {
      const pName = answer.attachToExisting?.trim();
      if (!pName) return answer.skillNote || "";
      let text = `ADD_TO_PROJECT: ${pName} `;
      if (answer.projectTech) text += `(Tech: ${answer.projectTech}) `;
      if (answer.projectDescription) text += `— ${answer.projectDescription} `;
      if (answer.skillNote) text += `| User Knowledge: ${answer.skillNote}`;
      return text.trim();
    }
  }
  
  return answer.skillNote || "";
}

function serializeExperienceEntry(e: ExperienceEntry): string {
  if (!e.company && !e.description) return "";
  let line = "";
  if (e.company) line += `Company: ${e.company}`;
  if (e.jobTitle) line += ` | Role: ${e.jobTitle}`;
  if (e.startDate) line += ` | From: ${e.startDate}`;
  if (e.endDate) line += ` to ${e.endDate}`;
  if (e.description) line += `\nDetails: ${e.description}`;
  return line.trim();
}

function serializeProjectEntry(p: ProjectEntry): string {
  if (!p.name && !p.description && !p.tech) return "";
  if (p.generateWithAI) {
    return `GENERATE_PROJECT: ${p.tech} | Name: ${p.name || 'Basic Project'}`;
  }
  let line = "project: " + (p.name || "");
  if (p.tech) line += ` (Tech: ${p.tech})`;
  if (p.description) line += ` — ${p.description}`;
  if (p.url) line += ` | URL: ${p.url}`;
  return line.trim();
}

// ── ScoreComparisonBanner ──────────────────────────────────────────────────────

function ScoreGauge({ label, score, projected, color }: { label: string; score: number | null; projected: number; color: string }) {
  const orig = score ?? 0;
  const gain = projected - orig;
  return (
    <div className="flex-1 min-w-[140px] bg-slate-800/60 border border-slate-700 rounded-xl p-4">
      <p className="text-zinc-500 text-xs font-semibold uppercase tracking-widest mb-3">{label}</p>
      <div className="flex items-end gap-3">
        {/* Original */}
        <div className="text-center">
          <div className={`text-3xl font-bold ${orig < 50 ? 'text-red-400' : orig < 70 ? 'text-amber-400' : 'text-emerald-400'}`}>
            {score !== null ? orig : '—'}
          </div>
          <p className="text-zinc-600 text-[10px] mt-1">Original</p>
        </div>
        {/* Arrow */}
        <TrendingUp size={18} className={`mb-2 ${color} shrink-0`} />
        {/* Projected */}
        <div className="text-center">
          <div className={`text-3xl font-bold ${color}`}>{projected}</div>
          <p className="text-zinc-600 text-[10px] mt-1">Projected</p>
        </div>
      </div>
      {gain > 0 && (
        <div className={`mt-3 inline-flex items-center gap-1 text-xs font-semibold px-2 py-0.5 rounded-full ${color} bg-current/10`}>
          <span className="opacity-80">↑ +{gain} pts after upgrade</span>
        </div>
      )}
    </div>
  );
}

function ScoreComparisonBanner({
  session,
  selectedImprovementsCount,
  addressedGapsCount,
  totalGapsCount,
}: {
  session: SessionDetail;
  selectedImprovementsCount: number;
  addressedGapsCount: number;
  totalGapsCount?: number;
}) {
  const ea = session.enhanced_analysis;
  const origMatch = ea?.match_score ?? null;
  const origAts = ea?.ats_score ?? null;

  const totalImprovements = ea?.improvements?.length || 0;
  const totalGaps = totalGapsCount ?? (ea?.gaps?.length || 0);

  // Projected score: purely proportional to actions taken
  // ATS: each terminology improvement checked = proportional share of missing ATS points
  const atsGain = totalImprovements > 0
    ? Math.round((selectedImprovementsCount / totalImprovements) * Math.max(0, 100 - (origAts ?? 0)) * 0.85)
    : 0;

  // Match: each gap addressed = proportional share of missing match points
  const matchGain = totalGaps > 0
    ? Math.round((addressedGapsCount / totalGaps) * Math.max(0, 100 - (origMatch ?? 0)) * 0.85)
    : 0;

  // Projected improvements
  const projMatch = Math.min(100, (origMatch ?? 40) + matchGain);
  const projAts = Math.min(100, (origAts ?? 55) + atsGain);

  return (
    <div className="bg-slate-900/80 border border-slate-700/60 rounded-2xl p-5 mb-2 transition-all duration-300">
      <div className="flex items-center gap-2 mb-4">
        <TrendingUp size={16} className="text-indigo-400" />
        <p className="text-zinc-300 text-sm font-semibold">Live Score Projection</p>
        <span className="text-zinc-600 text-xs ml-1 hidden sm:inline">— dynamically updates as you select improvements and address gaps</span>
      </div>
      <div className="flex flex-wrap gap-4">
        <ScoreGauge label="JD Match Score" score={origMatch} projected={projMatch} color="text-indigo-400" />
        <ScoreGauge label="ATS Score" score={origAts} projected={projAts} color="text-emerald-400" />
      </div>
    </div>
  );
}

